    -- Helper function: build hexagram from integer fields
    ---------------------------------------------------------------------------
    function make_hexagram(
        id_val     : integer;
        yao_val    : integer;
        up_tri     : integer;
        lo_tri     : integer;
        cat_val    : integer;
        act_val    : integer;
        agt_val    : integer;
        dom_val    : integer;
        elem_val   : integer;
        coder_val  : integer;
        rs3_val    : integer;
        mot_val    : integer;
        voice_val  : integer;
        intent_val : integer;
        dens_val   : integer;
        vtx_val    : integer;
        suc_val    : integer;
        chaos_val  : integer;
        whims_val  : integer;
        dark_val   : integer;
        coh_val    : integer;
        vw_val     : integer;
        intens_val : integer;
        tx_val     : integer;
        ty_val     : integer
    ) return t_hexagram is
        variable h : t_hexagram;
        variable mot_bit : std_logic;
    begin
        if mot_val = 0 then
            mot_bit := '0';
        else
            mot_bit := '1';
        end if;

        h.id             := to_unsigned(id_val, 7);
        h.yao            := to_unsigned(yao_val, 6);
        h.upper_trigram  := to_unsigned(up_tri, 3);
        h.lower_trigram  := to_unsigned(lo_tri, 3);
        h.category       := to_unsigned(cat_val, 2);
        h.action         := to_unsigned(act_val, 2);
        h.agent          := to_unsigned(agt_val, 2);
        h.domain         := to_unsigned(dom_val, 2);
        h.element        := to_unsigned(elem_val, 3);
        h.coder          := to_unsigned(coder_val, 4);
        h.rs3            := to_unsigned(rs3_val, 4);
        h.motion         := mot_bit;
        h.voice          := to_unsigned(voice_val, 4);
        h.intent         := to_unsigned(intent_val, 4);
        h.density        := to_unsigned(dens_val, 2);
        h.vortex_tension := to_signed(vtx_val, 16);
        h.suction        := to_unsigned(suc_val, 16);
        h.chaos          := to_unsigned(chaos_val, 16);
        h.whimsy         := to_unsigned(whims_val, 16);
        h.dark           := to_unsigned(dark_val, 16);
        h.coherence      := to_unsigned(coh_val, 16);
        h.voice_weight   := to_unsigned(vw_val, 16);
        h.intensity      := to_unsigned(intens_val, 16);
        h.tx             := to_signed(tx_val, 16);
        h.ty             := to_signed(ty_val, 16);
        return h;
    end function;

